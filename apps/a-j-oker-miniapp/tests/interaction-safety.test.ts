import { createElement, useEffect } from "react";
import { Checkbox, CheckboxGroup } from "@tarojs/components";
import { act, create, type ReactTestRenderer } from "react-test-renderer";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
const platform = vi.hoisted(() => ({ showModal: vi.fn(), navigateTo: vi.fn(), navigateBack: vi.fn(), makePhoneCall: vi.fn(), getCurrentPages: () => ["chat", "safety"] }));
const api = vi.hoisted(() => ({ getInteractionStatus: vi.fn(), interactionAction: vi.fn() }));
vi.mock("@tarojs/taro", () => ({ default: platform, useDidShow: (fn: () => void) => useEffect(fn, []) }));
vi.mock("@tarojs/components", () => ({ Button: "button", View: "view", Text: "text", Input: "input", Checkbox: "checkbox", CheckboxGroup: "checkbox-group", Label: "label", ScrollView: "scroll-view" }));
vi.mock("../src/chat/api", () => api);
import SafetyPage from "../src/pages/safety/index";
import { InteractionGuard } from "../src/chat/interaction";
const status = { activeMs: 0, notice: null, contact: null, contactNotice: "仅用于紧急联络", contactVersion: "2026-10-24.v1", support: { phone: "13000000000", hours: "合成值守安排", alertConfigured: false } };
let renderer: ReactTestRenderer;
const button = (text: string) => renderer.root.findAllByType("button").find((b) => b.children.includes(text) || b.findAllByType("text").some((t) => t.children.join("") === text))!;
beforeEach(() => { vi.resetAllMocks(); api.getInteractionStatus.mockResolvedValue(status); api.interactionAction.mockResolvedValue(status); platform.makePhoneCall.mockResolvedValue({}); });
afterEach(() => { act(() => renderer?.unmount()); vi.useRealTimers(); vi.unstubAllGlobals(); });
it("联系人用途须分别确认；保存与打开页面均不自动拨号", async () => {
  await act(async () => { renderer = create(createElement(SafetyPage)); });
  expect(renderer.root.findAllByType(Checkbox).every((c) => !c.props.checked)).toBe(true);
  act(() => { const fields = renderer.root.findAllByType("input"); fields[0].props.onInput({ detail: { value: "合成联系人" } }); fields[1].props.onInput({ detail: { value: "13000000000" } }); });
  act(() => renderer.root.findByType(CheckboxGroup).props.onChange({ detail: { value: ["consent"] } }));
  expect(button("保存联系人及单独授权").props.disabled).toBe(true);
  expect(api.interactionAction).not.toHaveBeenCalled();
  act(() => renderer.root.findByType(CheckboxGroup).props.onChange({ detail: { value: ["consent", "informed"] } }));
  await act(async () => { button("保存联系人及单独授权").props.onClick(); });
  expect(api.interactionAction).toHaveBeenCalledWith("contact", { name: "合成联系人", phone: "13000000000", consent: true, contactInformed: true, version: status.contactVersion });
  expect(platform.makePhoneCall).not.toHaveBeenCalled();
  await act(async () => { button("拨打人工联系电话").props.onClick(); });
  expect(platform.makePhoneCall).toHaveBeenCalledWith({ phoneNumber: "13000000000" });
});
it("移除联系人失败不伪造撤销成功，成功后才清除页面资料", async () => {
  api.getInteractionStatus.mockResolvedValue({ ...status, contact: { name: "合成联系人", phone: "13000000000", consentedAt: "2026-10-24T00:00:00Z" } });
  api.interactionAction.mockRejectedValueOnce(new Error("网络失败")).mockResolvedValueOnce(status);
  await act(async () => { renderer = create(createElement(SafetyPage)); });
  await act(async () => { button("移除并撤销授权").props.onClick(); });
  expect(JSON.stringify(renderer.toJSON())).toContain("网络失败");
  expect(JSON.stringify(renderer.toJSON())).toContain("合成联系人");
  await act(async () => { button("移除并撤销授权").props.onClick(); });
  expect(JSON.stringify(renderer.toJSON())).not.toContain("合成联系人");
  expect(JSON.stringify(renderer.toJSON())).toContain("已移除联系人");
});
it("未进入聊天或页面隐藏时不累计心跳；关闭页面停止计时请求", async () => {
  vi.useFakeTimers(); vi.stubGlobal("document", { visibilityState: "hidden" });
  await act(async () => { renderer = create(createElement(InteractionGuard, { enabled: true, revision: 0, onUnavailable: vi.fn() })); });
  await act(async () => { vi.advanceTimersByTime(30_000); });
  expect(api.interactionAction).not.toHaveBeenCalled();
  vi.stubGlobal("document", { visibilityState: "visible" });
  await act(async () => { vi.advanceTimersByTime(30_000); });
  expect(api.interactionAction).toHaveBeenCalledTimes(1);
  act(() => renderer.update(createElement(InteractionGuard, { enabled: false, revision: 0, onUnavailable: vi.fn() })));
  await act(async () => { vi.advanceTimersByTime(60_000); });
  expect(api.interactionAction).toHaveBeenCalledTimes(1);
});
it("提醒确认绑定原通知编号，未确认不提前清除，也不会反复弹同一个提醒", async () => {
  vi.useFakeTimers(); const notice = { id: "synthetic-notice", kind: "duration", text: "请暂停休息" };
  api.interactionAction.mockImplementation(async (action) => action === "heartbeat" ? { ...status, notice } : status);
  let resolve!: (answer: { confirm: boolean }) => void;
  platform.showModal.mockReturnValue(new Promise((r) => { resolve = r; }));
  await act(async () => { renderer = create(createElement(InteractionGuard, { enabled: true, revision: 0, onUnavailable: vi.fn() })); });
  expect(api.interactionAction.mock.calls.every(([a]) => a === "heartbeat")).toBe(true);
  await act(async () => { resolve({ confirm: false }); });
  expect(api.interactionAction).toHaveBeenCalledWith("acknowledge", { id: notice.id });
  await act(async () => { vi.advanceTimersByTime(30_000); });
  expect(platform.showModal).toHaveBeenCalledTimes(1); expect(platform.navigateTo).not.toHaveBeenCalled();
});
