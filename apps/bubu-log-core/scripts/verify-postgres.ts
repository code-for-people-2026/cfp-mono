  await pool.query(`UPDATE "AuditLog" SET input_text=$1,before_data=$2 WHERE id IN ('la','la2')`, ['photo '+url, { poopPhotoUrl: url }]);
  const media = new OriginalMediaReferences(pool, { old: "a" });
  const inventory = await media.inventory(); assert.equal(inventory.references.length, 3);
  const ref = inventory.references[0]!;
  await assert.rejects(() => media.replace({ ...ref, babyId: "b" }, privateUri), { code: "MEDIA_REFERENCE_CHANGED" });
  await media.replace(ref, privateUri); await media.replace(ref, privateUri);
  assert.equal((await media.inventory()).references[0]?.url, privateUri);
  const migratedAudit = (await pool.query(`SELECT input_text,before_data FROM "AuditLog" WHERE id IN ('la','la2')`)).rows;
  assert(migratedAudit.every(row => row.input_text === 'photo '+privateUri && row.before_data.poopPhotoUrl === privateUri));
  const oldOnly = 'https://photos.example.test/deleted-photo.png';
  await pool.query(`UPDATE "AuditLog" SET before_data=$1 WHERE id='la3'`, [{ poopPhotoUrl: oldOnly }]);
  const auditOnly = (await media.inventory()).references.find(row => row.url === oldOnly)!;
  assert.equal(auditOnly.kind, 'audit-photo');
