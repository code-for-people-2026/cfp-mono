  await assert.rejects(() => media.inventory(), { code: "LEGACY_AUDIT_SCOPE_CONFLICT" });
  await assert.rejects(() => new PostgresFamilyLifecycle(pool, { old: "a" }).deleteFamilyData("a"), { code: "LEGACY_AUDIT_SCOPE_CONFLICT" });
