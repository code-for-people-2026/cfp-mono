import { beforeAll, afterAll, describe, expect, it, vi } from "vitest";
import { mkdtemp, rm, readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash, randomUUID } from "node:crypto";
import { tmpdir } from "node:os";
import path from "node:path";
import sharp from "sharp";
import { openStore, type Store } from "../src/store";
import { IdentityService } from "../src/identity";
import { recordCollections, hash } from "../src/records/persistence";
import { chatCollections } from "../src/chat/persistence";
import { privacyCollections } from "../src/privacy/persistence";
import { PrivacyMaintenance } from "../src/privacy/maintenance";
import { PrivacyService } from "../src/privacy/service";
import { DeletionService } from "../src/privacy/deletion";
import { DeletionLedger } from "../src/privacy/deletion-ledger";
import { AttachmentService } from "../src/records/attachments";
import { LegacyFixture, WechatFixture } from "./fixtures/identity";
import { testPrivacyConfig } from "./fixtures/privacy";

describe("confirmed deletion, retries and restoring a snapshot", () => {
  let directory: string, store: Store, identity: IdentityService, privacy: PrivacyService, attachments: AttachmentService, ledger: DeletionLedger, deletion: DeletionService;
  const legacy = new LegacyFixture(); let failRemote = false, remoteCalls = 0, failAccount = false; const removedAccounts: string[] = [];
  let serial = 0;
  beforeAll(async () => {
    directory = await mkdtemp(path.join(tmpdir(), "bubu-deletion-test-"));
    store = await openStore({ directory: path.join(directory, "data"), extensions: [...recordCollections, ...chatCollections, ...privacyCollections] });
    identity = new IdentityService(store, legacy, new WechatFixture()); ledger = new DeletionLedger(path.join(directory, "ledger", "deletions.ndjson"));
    privacy = new PrivacyService(identity, testPrivacyConfig, ledger); identity.setProcessingGuard((scope, permission) => privacy.guard(scope, permission));
    identity.setLegacyAccountGuard(id => privacy.requireLegacyAccount(id));
    identity.setAccountChangeGuard(id => privacy.requireIdentityChange(id));
    attachments = new AttachmentService(identity, { directory: path.join(directory, "data"), beforeLegacyAccess: babyId => privacy.requireLegacyStorage(babyId) });
    deletion = new DeletionService(privacy, attachments, ledger, { exportFamilyData: async babyId => ({ babyId }), deleteFamilyData: async () => { remoteCalls++; if (failRemote) throw new Error("Synthetic upstream unavailable"); } }, { exportAccountData: async userId => ({ userId, profile: { name: "Synthetic caregiver" } }), deleteAccountData: async userId => { if (failAccount) throw new Error("Synthetic account failure"); removedAccounts.push(userId); } });
  }, 30000);
  afterAll(async () => { await store?.close(); await rm(directory, { recursive: true, force: true }); });
  async function family() {
    const suffix = ++serial, username = `synthetic-user-${suffix}`, babyId = `synthetic-baby-${suffix}`;
    legacy.users.add(username); legacy.memberships.set(username, [babyId]); legacy.babies.set(babyId, { id: babyId, name: "合成测试" });
    const principal = await identity.authenticate((await identity.loginLegacy(username, "correct-password", "native")).token);
    const policyVersion = privacy.policy().version;
    await privacy.consent(principal, { policyVersion, accepted: true, adultCaregiver: true, sensitive: true, ai: true, images: true });
    await privacy.guardian(principal, babyId, { policyVersion, guardian: true, sensitive: true, ai: true, images: true, collection: false, groupMembersInformed: false });
    const bytes = await sharp({ create: { width: 2, height: 2, channels: 3, background: "red" } }).png().toBuffer();
    const attachment = await attachments.upload(principal, babyId, bytes, "image/png", `privacy-image-${suffix}`);
    return { principal, babyId, attachment, username };
  }
  it("requires exact recent confirmation and never grants cross-family rights", async () => {
    const a = await family(), b = await family();
    await expect(deletion.prepare(b.principal, "family", a.babyId)).rejects.toMatchObject({ code: "BABY_FORBIDDEN" });
    const intent = await deletion.prepare(a.principal, "family", a.babyId);
    await expect(deletion.confirm(b.principal, intent.token, intent.confirmation)).rejects.toMatchObject({ code: "DELETION_INTENT_INVALID" });
    await expect(deletion.confirm(a.principal, intent.token, "确认")).rejects.toMatchObject({ code: "DELETION_CONFIRMATION_REQUIRED" });
    expect(ledger.read()).toHaveLength(0);
    expect((await attachments.read(a.principal, a.babyId, a.attachment.id)).bytes.length).toBeGreaterThan(0);
  });
  it("freezes before cleanup, retries failures, preserves other families and keeps the ledger outside DB state", async () => {
    const a = await family(), b = await family();
    const intent = await deletion.prepare(a.principal, "family", a.babyId);
    const receipt = await deletion.confirm(a.principal, intent.token, intent.confirmation);
    expect(await deletion.confirm(a.principal, intent.token, intent.confirmation)).toEqual(receipt);
    await expect(attachments.read(a.principal, a.babyId, a.attachment.id)).rejects.toMatchObject({ code: "PRIVACY_PROCESSING_FROZEN" });
    expect(await deletion.hasCompletedFamilyDeletion(a.babyId)).toBe(false);
    failRemote = true; await deletion.processPending();
    expect((await deletion.jobs(a.principal))[0]?.status).toBe("retry");
    expect(await store.payload.count({ collection: "care-attachments", where: { babyId: { equals: a.babyId } } })).toMatchObject({ totalDocs: 1 });
    failRemote = false; await deletion.processPending();
    expect((await deletion.jobs(a.principal))[0]?.status).toBe("completed");
    expect(await deletion.hasCompletedFamilyDeletion(a.babyId)).toBe(true);
    expect(await deletion.hasCompletedFamilyDeletion(b.babyId)).toBe(false);
    expect(await store.payload.count({ collection: "care-attachments", where: { babyId: { equals: a.babyId } } })).toMatchObject({ totalDocs: 0 });
    expect((await attachments.read(b.principal, b.babyId, b.attachment.id)).bytes.length).toBeGreaterThan(0);
    expect(ledger.frozen("family", a.babyId)).toBe(true);
    expect(remoteCalls).toBeGreaterThanOrEqual(2);
    await expect(privacy.guardian(a.principal, a.babyId, { policyVersion: privacy.policy().version, guardian: true, sensitive: true, ai: true, images: true, collection: false, groupMembersInformed: false })).rejects.toMatchObject({ code: "PRIVACY_PROCESSING_FROZEN" });
  });
  it("replays completed deletions after a restored snapshot and removes unreferenced restored objects", async () => {
    const a = await family(), intent = await deletion.prepare(a.principal, "family", a.babyId);
    const saved = await store.payload.findByID({ collection: "care-attachments", id: a.attachment.id });
    const objectPath = path.join(directory, "data", "private-attachments", hash(a.babyId), a.attachment.sha256);
    const ciphertext = await readFile(objectPath);
    await deletion.confirm(a.principal, intent.token, intent.confirmation); await deletion.processPending();
    // Simulate an old DB/media snapshot, including a blob omitted from its attachment rows.
    await store.transaction(req => store.payload.create({ collection: "care-attachments", data: saved, overrideAccess: true, req }));
    await mkdir(path.dirname(objectPath), { recursive: true }); await writeFile(objectPath, ciphertext);
    await writeFile(path.join(path.dirname(objectPath), "f".repeat(64)), Buffer.from("orphan"));
    await expect(attachments.read(a.principal, a.babyId, a.attachment.id)).rejects.toMatchObject({ code: "PRIVACY_PROCESSING_FROZEN" });
    await deletion.replayAfterRestore();
    expect((await store.payload.count({ collection: "care-attachments", where: { babyId: { equals: a.babyId } } })).totalDocs).toBe(0);
    await expect(readFile(objectPath)).rejects.toMatchObject({ code: "ENOENT" });
  });
  it("deletes private data from proof-merged identities while retaining shared family records", async () => {
    const f = await family(), other = await family();
    const source = await identity.authenticate((await identity.loginWechat("app:merged-source:one")).token);
    const policyVersion = privacy.policy().version;
    await privacy.consent(source, { policyVersion, accepted: true, adultCaregiver: true, sensitive: true, ai: true, images: true });
    const inviter = await identity.authenticate((await identity.provisionOperator("synthetic-inviter", f.babyId, 60000)).token);
    await identity.acceptInvite(source, (await identity.invite(inviter, f.babyId, "write")).code);
    const image = await sharp({ create: { width: 3, height: 2, channels: 3, background: "blue" } }).png().toBuffer();
    const privatePhoto = await attachments.upload(source, f.babyId, image, "image/png", "merged-private-photo");
    const sharedPhoto = await attachments.upload(source, f.babyId, image, "image/png", "merged-shared-photo");
    const chatId = randomUUID(), eventId = randomUUID();
    await identity.exclusive(async () => {
      await store.payload.create({ collection: "chat-turns", data: { id: chatId, key: chatId, identityId: source.subjectId, babyId: f.babyId, value: { input: { text: "merged private conversation" }, status: "completed" } }, overrideAccess: true, req: store.currentRequest() });
      await store.payload.create({ collection: "care-events", data: { id: eventId, key: eventId, babyId: f.babyId, value: { attachmentIds: [sharedPhoto.id], facts: { type: "POOP" } } }, overrideAccess: true, req: store.currentRequest() });
    });
    const merged = await identity.authenticate((await identity.bindLegacy(source, f.username, "correct-password")).token);
    expect(merged.subjectId).toBe(f.principal.subjectId);
    expect((await deletion.export(merged)).privateChat).toHaveLength(1);
    const intent = await deletion.prepare(merged, "account"); await deletion.confirm(merged, intent.token, intent.confirmation);
    expect(ledger.frozen("account", source.subjectId)).toBe(true);
    const late = await identity.authenticate((await identity.loginWechat("app:late-merge-source:one")).token);
    await privacy.consent(late, { policyVersion, accepted: true, adultCaregiver: true, sensitive: true, ai: true, images: true });
    await expect(identity.bindLegacy(late, f.username, "correct-password")).rejects.toMatchObject({ code: "LEGACY_ACCOUNT_DELETED" });
    expect(await identity.accountIdentityIds(merged.subjectId)).not.toContain(late.subjectId);
    await deletion.processPending();
    expect((await store.payload.count({ collection: "chat-turns", where: { identityId: { equals: source.subjectId } } })).totalDocs).toBe(0);
    expect(await store.get("identities", `subject:${source.subjectId}`)).toBeUndefined();
    expect(await store.get("identities", `subject:${merged.subjectId}`)).toBeUndefined();
    expect((await store.payload.count({ collection: "care-attachments", where: { key: { equals: privatePhoto.id } } })).totalDocs).toBe(0);
    expect((await store.payload.count({ collection: "care-attachments", where: { key: { equals: sharedPhoto.id } } })).totalDocs).toBe(1);
    expect((await store.payload.count({ collection: "care-events", where: { key: { equals: eventId } } })).totalDocs).toBe(1);
    expect((await attachments.read(other.principal, other.babyId, other.attachment.id)).bytes.length).toBeGreaterThan(0);
    // Another proved family manager may explicitly become the guardian; deletion is not implicit consent.
    legacy.memberships.set(other.username, [other.babyId, f.babyId]);
    expect((await privacy.status(other.principal, f.babyId)).guardianCurrent).toBe(false);
    expect((await privacy.status(other.principal, f.babyId)).guardian?.replaceable).toBe(true);
    await privacy.guardian(other.principal, f.babyId, { policyVersion, guardian: true, sensitive: true, ai: false, images: true, collection: false, groupMembersInformed: false });
    await attachments.read(other.principal, f.babyId, sharedPhoto.id);
  });
  it("freezes stable legacy credentials before deletion and does not recover grants after a fresh login or restored alias", async () => {
    const f = await family();
    const exported = await deletion.export(f.principal);
    expect(exported.account).toEqual([{userId:f.username,profile:{name:"Synthetic caregiver"}}]);
    const intent = await deletion.prepare(f.principal,"account");
    expect(intent.confirmation).toBe("注销我的账号和已绑定原版账号");
    await deletion.confirm(f.principal,intent.token,intent.confirmation);
    expect(ledger.read().find(row => row.identityId === f.principal.subjectId)?.legacyUserIds).toEqual([f.username]);
    await expect(identity.loginLegacy(f.username,"correct-password","native")).rejects.toMatchObject({code:"LEGACY_ACCOUNT_DELETED"});
    const newWechat = await identity.authenticate((await identity.loginWechat("app:fresh-after-deletion:one")).token);
    await expect(identity.bindLegacy(newWechat,f.username,"correct-password")).rejects.toMatchObject({code:"LEGACY_ACCOUNT_DELETED"});
    failAccount = true; await deletion.processPending();
    expect((await deletion.jobs(f.principal))[0]?.status).toBe("retry");
    failAccount = false; await deletion.processPending();
    expect(removedAccounts).toContain(f.username);
    // Fixture deliberately retains remote credentials to simulate a restored old User row.
    await expect(identity.loginLegacy(f.username,"correct-password","native")).rejects.toMatchObject({code:"LEGACY_ACCOUNT_DELETED"});
    await deletion.replayAfterRestore();
    expect(removedAccounts.filter(id => id === f.username).length).toBeGreaterThanOrEqual(2);
    expect(await identity.accountLegacyUserIds(newWechat.subjectId)).toEqual([]);
  });
  it("includes a proven upstream account when family creation committed but its response was lost", async () => {
    const principal = await identity.authenticate((await identity.loginWechat(`app:lost-family-${++serial}:one`)).token);
    await privacy.consent(principal, { policyVersion: privacy.policy().version, accepted: true, adultCaregiver: true, sensitive: true, ai: true, images: true });
    legacy.failFamilyOnce = true;
    await expect(identity.createFamily(principal,"合成测试")).rejects.toMatchObject({status:502});
    const remote = legacy.families.get(principal.subjectId)!;
    expect((await store.get("identities",`family:${principal.subjectId}`))?.value.state).toBeUndefined();
    expect((await deletion.export(principal)).account).toEqual([{userId:remote.userId,profile:{name:"Synthetic caregiver"}}]);
    const intent = await deletion.prepare(principal,"account");
    expect(intent.confirmation).toBe("注销我的账号和已绑定原版账号");
    await deletion.confirm(principal,intent.token,intent.confirmation);
    expect(ledger.read().find(row=>row.identityId === principal.subjectId)?.legacyUserIds).toEqual([remote.userId]);
    await deletion.processPending();
    expect(removedAccounts).toContain(remote.userId);
    expect(legacy.babies.has(remote.baby.id)).toBe(true);
    await expect(identity.loginLegacy(remote.userId,"correct-password","native")).rejects.toMatchObject({code:"LEGACY_ACCOUNT_DELETED"});
  });
  it("does not discard an unresolved provisioning journal or expand a version-one intent", async () => {
    const principal = await identity.authenticate((await identity.loginWechat(`app:unknown-family-${++serial}:one`)).token);
    const old = await deletion.prepare(principal,"account");
    const key = `intent:${createHash("sha256").update(old.token).digest("hex")}`;
    const prior = await privacy.repository.get<Record<string,unknown>>("privacy-state",key);
    await privacy.repository.put("privacy-state",key,{...prior,contractVersion:1},{identityId:principal.subjectId});
    await expect(deletion.confirm(principal,old.token,old.confirmation)).rejects.toMatchObject({code:"DELETION_SCOPE_CHANGED"});
    await store.put("identities",`family:${principal.subjectId}`,{name:"未核实创建"});
    await expect(deletion.prepare(principal,"account")).rejects.toMatchObject({code:"FAMILY_PROVISIONING_UNRESOLVED"});
    expect(ledger.read().some(row=>row.identityId === principal.subjectId)).toBe(false);
    expect(await store.get("identities",`family:${principal.subjectId}`)).not.toBeNull();
  });
  it("requires a new explicit intent when an account was bound after the confirmation screen", async () => {
    const f = await family();
    const person = await identity.authenticate((await identity.loginWechat("app:scope-change:one")).token);
    const intent = await deletion.prepare(person,"account");
    const linked = await identity.bindLegacy(person,f.username,"correct-password");
    const current = await identity.authenticate(linked.token);
    // Merge changes the subject too; neither the previous token nor a changed binding can authorize expanded erasure.
    await expect(deletion.confirm(current,intent.token,intent.confirmation)).rejects.toMatchObject({code:"DELETION_INTENT_INVALID"});
    expect(ledger.legacyAccountFrozen(f.username)).toBe(false);
  });
  it("migrates verified plaintext, strips metadata, and cleans leftovers after interrupted cleanup", async () => {
    const f = await family();
    const bytes = await sharp({ create: { width: 8, height: 4, channels: 3, background: "red" } }).jpeg().withExif({ IFD0: { Artist: "private original" } }).toBuffer();
    const sha256 = createHash("sha256").update(bytes).digest("hex");
    const row = await store.payload.findByID({ collection: "care-attachments", id: f.attachment.id, overrideAccess: true });
    await identity.exclusive(() => store.payload.update({ collection: "care-attachments", id: row.id, data: { value: { ...row.value as object, mime: "image/jpeg", sha256, byteLength: bytes.length } }, overrideAccess: true, req: store.currentRequest() }));
    const original = path.join(directory, "data", "private-attachments", hash(f.babyId), sha256); await writeFile(original, bytes);
    expect(await attachments.migrateObjects()).toMatchObject({ plaintext: 1, applied: false });
    expect(await readFile(original)).toEqual(bytes);
    const interrupted = vi.spyOn(attachments, "purgeOrphanObjects").mockRejectedValueOnce(new Error("synthetic interrupted cleanup"));
    await expect(attachments.migrateObjects(true)).rejects.toThrow("synthetic interrupted cleanup"); interrupted.mockRestore();
    expect(await readFile(original)).toEqual(bytes);
    expect(await attachments.migrateObjects(true)).toMatchObject({ plaintext: 0, applied: true });
    await expect(readFile(original)).rejects.toMatchObject({ code: "ENOENT" });
    const result = await attachments.read(f.principal, f.babyId, f.attachment.id);
    expect((await sharp(result.bytes).metadata()).exif).toBeUndefined();
  });
  it("keeps migrated original record photos through orphan cleanup and deletes them with their family", async () => {
    const f = await family(), other = await family(), reference = { kind: "activity" as const, documentId: "original-photo-record" };
    const bytes = await sharp({ create: { width: 4, height: 3, channels: 3, background: "orange" } }).jpeg().withExif({ IFD0: { Artist: "private legacy metadata" } }).toBuffer();
    const imported = await attachments.importLegacy(f.babyId, reference, bytes, "image/jpeg");
    expect(await attachments.importLegacy(f.babyId, reference, bytes, "image/jpeg")).toEqual(imported);
    const result = await attachments.read(f.principal, f.babyId, imported.id);
    expect((await sharp(result.bytes).metadata()).exif).toBeUndefined();
    await expect(attachments.read(other.principal, other.babyId, imported.id)).rejects.toMatchObject({ status: 404 });
    await expect(attachments.verifyLegacy(other.babyId, reference, imported.id)).rejects.toThrow("ownership");
    const row = await store.payload.findByID({ collection: "care-attachments", id: imported.id, overrideAccess: true });
    await identity.exclusive(() => store.payload.update({ collection: "care-attachments", id: row.id, data: { value: { ...row.value as object, createdAt: "2000-01-01T00:00:00Z" } }, overrideAccess: true, req: store.currentRequest() }));
    await new PrivacyMaintenance(privacy, attachments, deletion).run(true);
    await attachments.verifyLegacy(f.babyId, reference, imported.id);
    const intent = await deletion.prepare(f.principal, "family", f.babyId); await deletion.confirm(f.principal, intent.token, intent.confirmation); await deletion.processPending();
    await expect(attachments.verifyLegacy(f.babyId, reference, imported.id)).rejects.toMatchObject({ code: "PRIVACY_PROCESSING_FROZEN" });
    await expect(attachments.importLegacy(f.babyId, reference, bytes, "image/jpeg")).rejects.toMatchObject({ code: "PRIVACY_PROCESSING_FROZEN" });
    await expect(readFile(path.join(directory, "data", "private-attachments", hash(f.babyId), imported.sha256))).rejects.toMatchObject({ code: "ENOENT" });
  });
  it("detects interrupted and modified ledger entries before trusting the deletion state", async () => {
    const file = path.join(directory, "corrupt.ndjson"), local = new DeletionLedger(file);
    local.append({ version: 1, jobId: randomUUID(), kind: "account", identityId: "synthetic", createdAt: new Date().toISOString() });
    const valid = await readFile(file, "utf8");
    await writeFile(file, valid.slice(0, -1)); expect(() => local.read()).toThrow("incomplete");
    await writeFile(file, valid.replace("synthetic", "changed")); expect(() => local.read()).toThrow("integrity");
  });
});
